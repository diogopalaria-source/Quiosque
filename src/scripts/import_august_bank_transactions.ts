  // Write August transactions in batches
  const batchSize = 400;
  for (let i = 0; i < processedItems.length; i += batchSize) {
    const chunk = processedItems.slice(i, i + batchSize);
    const batch = writeBatch(db);

    chunk.forEach(item => {
      const id = generateDeterministicId(item);
      const docRef = doc(db, collectionPath, id);
      batch.set(docRef, {
        ...item,
        userId: sharedUserId
      });
    });

    await batch.commit();
    console.log(`Committed August batch ${Math.floor(i / batchSize) + 1} (${chunk.length} items)`);
  }

  // System log
  const logRef = doc(collection(db, 'users/shared_franquia_data/systemLogs'));
  const logBatch = writeBatch(db);
