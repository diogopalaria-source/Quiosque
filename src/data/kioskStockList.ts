export type CountLocation = 'quiosque' | 'deposito' | 'estoque' | 'ambos';
export type StockCountType = 'unidade' | 'embalagem_com_aberto' | 'caixa_ou_avulso' | 'tem_bastante';

export interface PredefinedStockItem {
  id: string;
  produto: string;
  local: CountLocation; // 'quiosque' | 'estoque' | 'ambos'
  categoriaQuiosque?: string; // Categoria quando estiver no quiosque (Freezer, Expositor, Embaixo Air Fryer, etc)
  categoriaEstoque?: string; // Categoria quando estiver no estoque (Café, Insumos, Doces, Limpeza, etc). Deixe indefinido se local for apenas quiosque!
  categoria: string;
  minimo: number;
  tipoContagem: StockCountType;
  unidadeMedida: string;
  tamanhoCaixa?: number;
  rotuloEmbalagem?: string;
  ehBoloProducao?: boolean;
}

export const CAKE_PRODUCTION_NAMES = [
  'Bolo cenoura',
  'Bolo laranja',
  'Bolo chocolate',
  'Bolo coco',
  'Bolo banana',
  'Bolo milho'
];

export const isCakeProduction = (produtoName: string): boolean => {
  if (!produtoName) return false;
  const norm = produtoName.toLowerCase().trim();
  return CAKE_PRODUCTION_NAMES.some(c => norm.includes(c.toLowerCase()));
};

